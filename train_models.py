import os
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import roc_auc_score, average_precision_score


# ==============================================================================
# Configuration & Constants
# ==============================================================================

# Directory containing the certified artifacts generated by Member 2
SCRIPT_DIR = Path(__file__).resolve().parent
ARTIFACTS_DIR = SCRIPT_DIR / "tox21_member2_handoff" / "artifacts"
RESULTS_CSV_PATH = SCRIPT_DIR / "model_evaluation_results.csv"

# All 12 Tox21 toxicological endpoints
TARGET_ASSAYS = [
    "NR-AR",
    "NR-AR-LBD",
    "NR-AhR",
    "NR-Aromatase",
    "NR-ER",
    "NR-ER-LBD",
    "NR-PPAR-gamma",
    "SR-ARE",
    "SR-ATAD5",
    "SR-HSE",
    "SR-MMP",
    "SR-p53",
]


# ==============================================================================
# Step 1: Load Data & Precomputed Features
# ==============================================================================

def load_tox21_data(artifacts_dir: Path):
    """
    Loads preprocessed feature matrices and split metadata created by Members 1 and 2.
    
    Returns:
        X: numpy array of shape (7823, 2053) containing:
           - 2,048 binary Morgan fingerprint bits (radius=2)
           - 5 standardized continuous descriptors (MolWt, TPSA, MolLogP, NumHDonors, NumHAcceptors)
        labels_df: pandas DataFrame containing:
           - 'mol_id', 'split' (train, val, test)
           - 12 target assay label columns (0.0, 1.0, or NaN for missing)
    """
    labels_path = artifacts_dir / "labels_and_splits.parquet"
    features_path = artifacts_dir / "X_combined.parquet"

    if not labels_path.exists():
        raise FileNotFoundError(f"Missing labels artifact at: {labels_path}")
    if not features_path.exists():
        raise FileNotFoundError(f"Missing features artifact at: {features_path}")

    print(f"Loading metadata and scaffold splits from: {labels_path.name}")
    labels_df = pd.read_parquet(labels_path)

    print(f"Loading combined feature matrix from: {features_path.name}")
    features_df = pd.read_parquet(features_path)

    # Separate molecule ID and extract numeric features
    feat_cols = [col for col in features_df.columns if col != "mol_id"]
    X = features_df[feat_cols].values.astype(np.float64)

    return X, labels_df


# ==============================================================================
# Step 2: Initialize Basic Classifiers
# ==============================================================================

def get_models(random_state: int = 42):
    """
    Returns dictionaries of basic scikit-learn models with clean, beginner-friendly
    hyperparameters.
    
    Why class_weight='balanced'?
    Tox21 has severe class imbalance (only 2.5% to 15% active/toxic compounds).
    'balanced' automatically adjusts weights inversely proportional to class frequencies,
    preventing the model from ignoring the minority (toxic) class.
    """
    models = {
        "Logistic Regression": LogisticRegression(
            max_iter=1000,
            class_weight="balanced",
            random_state=random_state,
        ),
        "Decision Tree": DecisionTreeClassifier(
            max_depth=10,
            class_weight="balanced",
            random_state=random_state,
        ),
        "Random Forest": RandomForestClassifier(
            n_estimators=100,
            max_depth=12,
            class_weight="balanced",
            random_state=random_state,
            n_jobs=-1,
        ),
    }
    return models


# ==============================================================================
# Step 3: Train and Evaluate Models across all 12 Endpoints
# ==============================================================================

def train_and_evaluate_all():
    """
    Main training and evaluation routine:
    1. Iterates through all 12 Tox21 assays.
    2. Filters out missing labels (NaN) for each split.
    3. Fits Logistic Regression, Decision Tree, and Random Forest.
    4. Computes ROC-AUC and PR-AUC on Validation and Test sets.
    5. Saves detailed metrics to CSV and prints summary tables.
    """
    print("=" * 80)
    print("           Tox21 Molecular Toxicity Prediction - Model Training")
    print("=" * 80)

    # 1. Load data
    X, labels_df = load_tox21_data(ARTIFACTS_DIR)

    # Create boolean split masks
    train_mask = (labels_df["split"] == "train").values
    val_mask = (labels_df["split"] == "val").values
    test_mask = (labels_df["split"] == "test").values

    print(f"Total dataset size: {len(labels_df)} molecules")
    print(f"  - Train molecules: {train_mask.sum()} (~80%)")
    print(f"  - Val molecules:   {val_mask.sum()} (~10%)")
    print(f"  - Test molecules:  {test_mask.sum()} (~10%)")
    print(f"Total features per molecule: {X.shape[1]}")
    print("=" * 80)

    results = []
    start_total_time = time.time()

    # Loop over all 12 toxicity endpoints
    for assay_idx, assay in enumerate(TARGET_ASSAYS, start=1):
        print(f"\n[{assay_idx}/12] Processing Endpoint: {assay}")
        y_all = labels_df[assay].values

        # IMPORTANT REQUIREMENT:
        # Exclude missing labels (NaN) strictly. Never treat them as 0!
        train_obs = train_mask & ~np.isnan(y_all)
        val_obs = val_mask & ~np.isnan(y_all)
        test_obs = test_mask & ~np.isnan(y_all)

        X_train, y_train = X[train_obs], y_all[train_obs]
        X_val, y_val = X[val_obs], y_all[val_obs]
        X_test, y_test = X[test_obs], y_all[test_obs]

        n_train_pos = int((y_train == 1).sum())
        n_train_neg = int((y_train == 0).sum())
        n_test_pos = int((y_test == 1).sum())
        n_test_neg = int((y_test == 0).sum())

        print(f"   Train samples: {len(y_train)} (Pos: {n_train_pos}, Neg: {n_train_neg})")
        print(f"   Test samples:  {len(y_test)} (Pos: {n_test_pos}, Neg: {n_test_neg})")

        # Initialize fresh models for this endpoint
        models = get_models(random_state=42)

        for model_name, model in models.items():
            t0 = time.time()

            # Train model only on observed training samples
            model.fit(X_train, y_train)

            # Predict probabilities for positive class (toxic = 1)
            # predict_proba returns [prob_neg, prob_pos], so column 1 is prob_pos
            val_probs = model.predict_proba(X_val)[:, 1]
            test_probs = model.predict_proba(X_test)[:, 1]

            # Compute evaluation metrics:
            # 1. ROC-AUC: Measures discrimination across all thresholds (random guess = 0.50)
            # 2. PR-AUC: Precision-Recall Area Under Curve (Average Precision), highly informative for imbalanced data
            val_roc_auc = roc_auc_score(y_val, val_probs)
            val_pr_auc = average_precision_score(y_val, val_probs)

            test_roc_auc = roc_auc_score(y_test, test_probs)
            test_pr_auc = average_precision_score(y_test, test_probs)

            elapsed = time.time() - t0

            print(
                f"   -> {model_name:20s} | "
                f"Test ROC-AUC: {test_roc_auc:.4f} | "
                f"Test PR-AUC: {test_pr_auc:.4f} ({elapsed:.1f}s)"
            )

            # Record detailed results
            results.append({
                "endpoint": assay,
                "model": model_name,
                "train_total_samples": len(y_train),
                "train_positives": n_train_pos,
                "train_negatives": n_train_neg,
                "test_total_samples": len(y_test),
                "test_positives": n_test_pos,
                "test_negatives": n_test_neg,
                "val_roc_auc": round(val_roc_auc, 4),
                "val_pr_auc": round(val_pr_auc, 4),
                "test_roc_auc": round(test_roc_auc, 4),
                "test_pr_auc": round(test_pr_auc, 4),
            })

    total_time = time.time() - start_total_time
    print("\n" + "=" * 80)
    print(f"All 12 endpoints completed successfully in {total_time:.2f} seconds.")
    print("=" * 80)

    # Convert results to DataFrame
    results_df = pd.DataFrame(results)

    # Save results to CSV file
    results_df.to_csv(RESULTS_CSV_PATH, index=False)
    print(f"\nDetailed results saved to CSV: {RESULTS_CSV_PATH}")

    # Display Macro-Averaged Benchmark Summary
    print("\n" + "=" * 80)
    print("          BENCHMARK SUMMARY (AVERAGE OVER ALL 12 ENDPOINTS)")
    print("=" * 80)
    summary_df = results_df.groupby("model")[
        ["val_roc_auc", "val_pr_auc", "test_roc_auc", "test_pr_auc"]
    ].mean()

    summary_df = summary_df.rename(columns={
        "val_roc_auc": "Mean Val ROC-AUC",
        "val_pr_auc": "Mean Val PR-AUC",
        "test_roc_auc": "Mean Test ROC-AUC",
        "test_pr_auc": "Mean Test PR-AUC",
    })
    summary_df = summary_df.round(4)
    print(summary_df.to_string())
    print("=" * 80)

    return results_df, summary_df


if __name__ == "__main__":
    train_and_evaluate_all()
